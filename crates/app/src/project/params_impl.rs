use super::*;

impl ParamsDto {
    pub(super) fn from_params(p: &OpParams) -> Self {
        match p {
            OpParams::Face {
                stepover,
                clearance_z,
                cut_z,
                top_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
            } => {
                ParamsDto::Face {
                    stepover: *stepover,
                    clearance_z: (*clearance_z).into(),
                    cut_z: (*cut_z).into(),
                    feed: *feed,
                    plunge_feed: *plunge_feed,
                    climb: *climb,
                    top_z: (*top_z).map(Into::into),
                    stepdown: *stepdown,
                }
            }
            OpParams::Contour {
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                lead,
                tolerance,
                tab_count,
                tab_width,
                tab_height,
                side,
            } => ParamsDto::Contour {
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).into(),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                lead: match lead {
                    Lead::None => LeadDto::None,
                    Lead::Linear { length } => LeadDto::Linear { length: *length },
                    Lead::Arc { radius } => LeadDto::Arc { radius: *radius },
                    Lead::Tangential { radius } => LeadDto::Tangential { radius: *radius },
                },
                tolerance: *tolerance,
                tab_count: *tab_count,
                tab_width: *tab_width,
                tab_height: *tab_height,
                side: match side {
                    Side::Auto => SideDto::Auto,
                    Side::Inside => SideDto::Inside,
                    Side::Outside => SideDto::Outside,
                },
            },
            OpParams::Pocket {
                stepover,
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                strategy,
            } => ParamsDto::Pocket {
                stepover: *stepover,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                strategy: match strategy {
                    PocketStrategy::Zigzag => StrategyDto::Zigzag,
                    PocketStrategy::Waterline => StrategyDto::Waterline,
                    PocketStrategy::Auto => StrategyDto::Auto,
                    PocketStrategy::Adaptive => StrategyDto::Adaptive,
                },
                // Absent means the hop-to-clearance every pre-step-5
                // pocket performed; a set plane round-trips exactly.
                retract_z: (*retract_z).map(Into::into),
            },
            OpParams::Pocket3D {
                stepover,
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                strategy,
                entry,
                helix_radius,
                rest_rough,
                max_engagement,
                feed_opt,
            } => ParamsDto::Pocket3D {
                stepover: *stepover,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                strategy: match strategy {
                    PocketStrategy::Zigzag => StrategyDto::Zigzag,
                    PocketStrategy::Waterline => StrategyDto::Waterline,
                    PocketStrategy::Auto => StrategyDto::Auto,
                    PocketStrategy::Adaptive => StrategyDto::Adaptive,
                },
                retract_z: (*retract_z).map(Into::into),
                entry: match entry {
                    Entry3D::Plunge => EntryDto::Plunge,
                    Entry3D::Ramp => EntryDto::Ramp,
                    Entry3D::Helix => EntryDto::Helix,
                },
                helix_radius: *helix_radius,
                rest_rough: *rest_rough,
                max_engagement: *max_engagement,
                feed_opt: *feed_opt,
            },
            OpParams::Finish3D {
                pattern,
                stepover,
                tolerance,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                feed,
                plunge_feed,
                climb,
                ramp,
                min_step,
                ramp_angle,
            } => ParamsDto::Finish3D {
                pattern: (*pattern).into(),
                stepover: *stepover,
                tolerance: *tolerance,
                clearance_z: (*clearance_z).into(),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                retract_z: (*retract_z).map(Into::into),
                ramp: *ramp,
                min_step: *min_step,
                ramp_angle: *ramp_angle,
            },
            OpParams::Slot {
                a,
                b,
                width,
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                stepover,
                feed,
                plunge_feed,
                climb,
            } => ParamsDto::Slot {
                a: [a.x, a.y],
                b: [b.x, b.y],
                width: *width,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                stepover: *stepover,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
            },
            OpParams::Trace {
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
            } => ParamsDto::Trace {
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
            },
            OpParams::Drill {
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                cycle,
                peck,
                dwell,
                feed,
                plunge_feed,
                holes,
            } => ParamsDto::Drill {
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).map(Into::into),
                cycle: match cycle {
                    CycleChoice::Auto => CycleChoiceDto::Auto,
                    CycleChoice::Spot => CycleChoiceDto::Spot,
                    CycleChoice::Drill => CycleChoiceDto::Drill,
                    CycleChoice::Peck => CycleChoiceDto::Peck,
                    CycleChoice::Tap => CycleChoiceDto::Tap,
                    CycleChoice::Bore => CycleChoiceDto::Bore,
                    CycleChoice::BackBore => CycleChoiceDto::BackBore,
                },
                peck: *peck,
                dwell: *dwell,
                feed: *feed,
                plunge_feed: *plunge_feed,
                holes: holes.iter().map(HoleDto::from_hole).collect(),
            },
        }
    }

    pub(super) fn to_params(&self) -> OpParams {
        match self {
            // Absent v5 keys decode (via serde defaults) to the legacy
            // single-level face, byte-exact; present ones land on the
            // domain as staged facing.
            ParamsDto::Face { stepover, clearance_z, cut_z, top_z, stepdown, feed, plunge_feed, climb } => {
                OpParams::Face {
                    stepover: *stepover,
                    clearance_z: (*clearance_z).into(),
                    cut_z: (*cut_z).into(),
                    top_z: (*top_z).map(Into::into),
                    stepdown: *stepdown,
                    feed: *feed,
                    plunge_feed: *plunge_feed,
                    climb: *climb,
                }
            }
            ParamsDto::Contour {
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                lead,
                tolerance,
                tab_count,
                tab_width,
                tab_height,
                side,
            } => OpParams::Contour {
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).into(),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                lead: match lead {
                    LeadDto::None => Lead::None,
                    LeadDto::Linear { length } => Lead::Linear { length: *length },
                    LeadDto::Arc { radius } => Lead::Arc { radius: *radius },
                    LeadDto::Tangential { radius } => Lead::Tangential { radius: *radius },
                },
                tolerance: *tolerance,
                tab_count: *tab_count,
                tab_width: *tab_width,
                tab_height: *tab_height,
                side: match side {
                    SideDto::Auto => Side::Auto,
                    SideDto::Inside => Side::Inside,
                    SideDto::Outside => Side::Outside,
                },
            },
            ParamsDto::Pocket {
                stepover,
                stock_to_leave,
                clearance_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                strategy,
                retract_z,
            } => OpParams::Pocket {
                stepover: *stepover,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                strategy: match strategy {
                    StrategyDto::Zigzag => PocketStrategy::Zigzag,
                    StrategyDto::Waterline => PocketStrategy::Waterline,
                    StrategyDto::Auto => PocketStrategy::Auto,
                    StrategyDto::Adaptive => PocketStrategy::Adaptive,
                },
            },
            ParamsDto::Pocket3D {
                stepover,
                stock_to_leave,
                clearance_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
                strategy,
                retract_z,
                entry,
                helix_radius,
                rest_rough,
                max_engagement,
                feed_opt,
            } => OpParams::Pocket3D {
                stepover: *stepover,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                strategy: match strategy {
                    StrategyDto::Zigzag => PocketStrategy::Zigzag,
                    StrategyDto::Waterline => PocketStrategy::Waterline,
                    StrategyDto::Auto => PocketStrategy::Auto,
                    StrategyDto::Adaptive => PocketStrategy::Adaptive,
                },
                entry: match entry {
                    EntryDto::Plunge => Entry3D::Plunge,
                    EntryDto::Ramp => Entry3D::Ramp,
                    EntryDto::Helix => Entry3D::Helix,
                },
                helix_radius: *helix_radius,
                rest_rough: *rest_rough,
                max_engagement: *max_engagement,
                feed_opt: *feed_opt,
            },
            ParamsDto::Finish3D {
                pattern,
                stepover,
                tolerance,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                feed,
                plunge_feed,
                climb,
                ramp,
                min_step,
                ramp_angle,
            } => OpParams::Finish3D {
                pattern: (*pattern).into(),
                stepover: *stepover,
                tolerance: *tolerance,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
                ramp: *ramp,
                min_step: *min_step,
                ramp_angle: *ramp_angle,
            },
            ParamsDto::Slot {
                a,
                b,
                width,
                stock_to_leave,
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                stepover,
                feed,
                plunge_feed,
                climb,
            } => OpParams::Slot {
                a: Point2::new(a[0], a[1]),
                b: Point2::new(b[0], b[1]),
                width: *width,
                stock_to_leave: *stock_to_leave,
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                stepover: *stepover,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
            },
            ParamsDto::Trace {
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                stepdown,
                feed,
                plunge_feed,
                climb,
            } => OpParams::Trace {
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).into(),
                stepdown: *stepdown,
                feed: *feed,
                plunge_feed: *plunge_feed,
                climb: *climb,
            },
            ParamsDto::Drill {
                clearance_z,
                retract_z,
                top_z,
                bottom_z,
                cycle,
                peck,
                dwell,
                feed,
                plunge_feed,
                holes,
            } => OpParams::Drill {
                clearance_z: (*clearance_z).into(),
                retract_z: (*retract_z).map(Into::into),
                top_z: (*top_z).into(),
                bottom_z: (*bottom_z).map(Into::into),
                cycle: match cycle {
                    CycleChoiceDto::Auto => CycleChoice::Auto,
                    CycleChoiceDto::Spot => CycleChoice::Spot,
                    CycleChoiceDto::Drill => CycleChoice::Drill,
                    CycleChoiceDto::Peck => CycleChoice::Peck,
                    CycleChoiceDto::Tap => CycleChoice::Tap,
                    CycleChoiceDto::Bore => CycleChoice::Bore,
                    CycleChoiceDto::BackBore => CycleChoice::BackBore,
                },
                peck: *peck,
                dwell: *dwell,
                feed: *feed,
                plunge_feed: *plunge_feed,
                holes: holes.iter().copied().map(HoleDto::to_hole).collect(),
            },
        }
    }
}
