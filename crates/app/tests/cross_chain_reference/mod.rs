pub fn assert_chain(path: &Toolpath, case: usize) {
    let expected = [THREE_STATION, OFF_CENTER][case];
    assert!(path.is_chained() && path.all_finite());
    assert!(path.cycles.is_empty() && path.comps.is_empty());
    assert_eq!(path.moves.len(), expected.len(), "cylinder case {case}: ordered move count");
    for (i, (got, &(kind, from, to, feed, axis))) in path.moves.iter().zip(expected).enumerate() {
        assert_eq!((got.kind, got.feed, got.axis, got.arc), (kind, feed, Some(axis), None), "cylinder case {case}: move {i} vocabulary");
        for (a, b) in [(got.from, from), (got.to, to)] {
            let b = Point3::new(b[0], b[1], b[2]);
            let delta = a - b;
            assert!(delta.dot(delta).sqrt() <= 1e-9, "cylinder case {case}: move {i}: {a:?} != {b:?}");
        }
    }
}
